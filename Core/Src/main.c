void USB_RXCallback(uint8_t* Buf, uint32_t *Len){
	/* LATENCY FIX: Keep the interrupt as short as possible.
	   Only copy the data and set the flag. No processing loops here. */
	if (*Len <= USB_BUFLEN) {
		memcpy(usbRxBuf, Buf, *Len);
		usbRxBufLen = *Len;
		usbRxFlag = 1;
	}
}
